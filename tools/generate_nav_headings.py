"""Writes docs/_data/nav_headings.yml: the second-level headings of every docs page (docs/*.md
and docs/web/*.md).

The docs site adds them under each page in the side menu (docs/_includes/head_custom.html and
docs/assets/js/nav-headings.js). The anchors are made the way the GitHub Pages Markdown parser
(kramdown with GFM) makes heading ids, so the links land on the headings.

Usage (from the repository root): python tools/generate_nav_headings.py
"""
import glob
import os
import re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
docs = os.path.join(root, 'docs')
out = os.path.join(docs, '_data', 'nav_headings.yml')

HEADING = re.compile(r'^(#{1,6})\s+(.*?)\s*#*\s*$')
FENCE = re.compile(r'^\s*(```|~~~)')


def heading_text(markdown):
    """Heading as shown: code spans, emphasis and links reduced to their text."""
    text = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', markdown)
    return re.sub(r'[`*_]', '', text).strip()


def gfm_id(text, counts):
    """kramdown's GFM header id: lower case, only word characters, hyphens and spaces, spaces to
    hyphens, and -1, -2, ... for repeats on the same page."""
    slug = re.sub(r'[^\w\- \t]', '', text.lower()).replace(' ', '-').replace('\t', '-')
    counts[slug] = counts.get(slug, 0) + 1
    return slug if counts[slug] == 1 else f'{slug}-{counts[slug] - 1}'


def page_headings(path):
    headings, counts, in_fence = [], {}, False
    with open(path, encoding='utf-8') as f:
        lines = f.read().split('\n')
    # Skip the front matter
    if lines and lines[0].strip() == '---':
        end = lines.index('---', 1) if '---' in lines[1:] else 0
        lines = lines[end + 1:]
    for line in lines:
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        match = None if in_fence else HEADING.match(line)
        if match:
            # Every level counts towards repeated ids, but only level 2 goes into the menu.
            anchor = gfm_id(match.group(2), counts)
            if len(match.group(1)) == 2:
                headings.append((anchor, heading_text(match.group(2))))
    return headings


def quote(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    lines = ['# Generated by tools/generate_nav_headings.py; do not edit.',
             '# Second-level headings of each page, keyed by the page\'s source path.']
    pages = glob.glob(os.path.join(docs, '*.md')) + glob.glob(os.path.join(docs, 'web', '*.md'))
    for path in sorted(pages, key=lambda p: os.path.relpath(p, docs).replace(os.sep, '/')):
        headings = page_headings(path)
        if headings:
            # Jekyll's page.path: relative to docs/, with forward slashes (web/buttons.md)
            lines.append(f'{os.path.relpath(path, docs).replace(os.sep, "/")}:')
            for anchor, title in headings:
                lines.append(f'  - id: {quote(anchor)}')
                lines.append(f'    title: {quote(title)}')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('Wrote', os.path.relpath(out, root))


if __name__ == '__main__':
    main()
