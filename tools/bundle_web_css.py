"""Writes src/JetPack.Web/wwwroot/css/jetpack.css, the one stylesheet a site links, from
jetpack.src.css: each @import of a local file is replaced by that file's contents.

One file can carry a version in its address (asp-append-version), so browsers fetch it again after an
update; the imported files of jetpack.src.css would be kept from the cache. The imported files sit in
css/ or css/controls/ and use no relative url() (the texture's is in jetpack.tokens.css, which is in
css/ like the bundle), so their text is copied as it is.

Edit jetpack.src.css, css/controls/*.css or the tokens (tools/generate_web_tokens.py), then run:
    python tools/bundle_web_css.py           write jetpack.css
    python tools/bundle_web_css.py --check   exit with 1 when jetpack.css is out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSS = os.path.join(ROOT, 'src', 'JetPack.Web', 'wwwroot', 'css')
SOURCE = os.path.join(CSS, 'jetpack.src.css')
OUT = os.path.join(CSS, 'jetpack.css')
IMPORT = re.compile(r'^@import url\("([^"]+)"\);\n', re.M)
HEADER = ('/* Generated by tools/bundle_web_css.py from jetpack.src.css and the files it imports; do not edit.\n'
          '   Sources: https://github.com/Montago/JetPackTheme/tree/master/src/JetPack.Web/wwwroot/css */\n')


def read(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def render():
    def inline(match):
        name = match.group(1)
        text = read(os.path.join(CSS, name)).rstrip('\n')
        return f'\n/* ---------------------------------------------------------------- {name} */\n{text}\n'
    return HEADER + IMPORT.sub(inline, read(SOURCE))


def main():
    css = render()
    if '--check' in sys.argv:
        if not os.path.exists(OUT) or read(OUT) != css:
            print('jetpack.css is out of date; run python tools/bundle_web_css.py')
            sys.exit(1)
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(css)
    print(f'wrote {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
