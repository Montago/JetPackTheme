"""Builds the JetPack icon set from icons/icons.json and the SVG files in icons/mdi/. Enum names are
the MDI names in PascalCase, as in MahApps' IconBrowser (view-grid -> ViewGrid):

    src/JetPack.Wpf/Controls/JetPackIconKind.g.cs     enum + path data for <jp:JetPackIcon Kind="..." />
    src/JetPack.Web/TagHelpers/JetPackIconKind.g.cs   the same enum for <jp-icon kind="..." />
    src/JetPack.Web/wwwroot/img/icons.svg             SVG sprite, one <symbol> per icon (id = MDI name)

The icons are Material Design Icons (Apache License 2.0, see icons/LICENSE). They are kept in the
repository, so building needs no network; --fetch downloads the ones the manifest lists but the
folder lacks, at the pinned package version.

Usage (from the repository root):
    python tools/generate_icons.py            write the files
    python tools/generate_icons.py --fetch    download missing SVGs first, then write
    python tools/generate_icons.py --check    exit with 1 when the files are out of date
"""
import json
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, 'icons')
SVG_DIR = os.path.join(ICONS, 'mdi')
OUT_WPF = os.path.join(ROOT, 'src', 'JetPack.Wpf', 'Controls', 'JetPackIconKind.g.cs')
OUT_WEB_ENUM = os.path.join(ROOT, 'src', 'JetPack.Web', 'TagHelpers', 'JetPackIconKind.g.cs')
OUT_SPRITE = os.path.join(ROOT, 'src', 'JetPack.Web', 'wwwroot', 'img', 'icons.svg')
SVG_NS = '{http://www.w3.org/2000/svg}'
HEADER = '// Generated by tools/generate_icons.py from icons/icons.json; do not edit.\n'


def pascal(mdi):
    """view-grid -> ViewGrid, the name MahApps' PackIconMaterialKind uses."""
    return ''.join(part[:1].upper() + part[1:] for part in mdi.split('-'))


def manifest():
    with open(os.path.join(ICONS, 'icons.json'), encoding='utf-8') as f:
        return json.load(f)


def fetch(data):
    base = f"https://cdn.jsdelivr.net/npm/{data['package']}@{data['version']}/"
    os.makedirs(SVG_DIR, exist_ok=True)
    wanted = [('LICENSE', os.path.join(ICONS, 'LICENSE'))]
    wanted += [(f'svg/{mdi}.svg', os.path.join(SVG_DIR, mdi + '.svg')) for mdi in data['icons']]
    for remote, target in wanted:
        if os.path.exists(target):
            continue
        with urllib.request.urlopen(base + remote, timeout=30) as response:
            content = response.read()
        with open(target, 'wb') as f:
            f.write(content)
        print('fetched', remote)


def path_data(mdi):
    """The d of the single 24x24 path in an MDI file."""
    root = ET.parse(os.path.join(SVG_DIR, mdi + '.svg')).getroot()
    if root.get('viewBox') != '0 0 24 24':
        raise ValueError(f'{mdi}.svg: expected viewBox 0 0 24 24')
    paths = [p.get('d') for p in root.iter(SVG_NS + 'path')]
    if len(paths) != 1:
        raise ValueError(f'{mdi}.svg: expected one path, found {len(paths)}')
    return paths[0]


def enum(namespace, icons, member):
    """The enum plus a lookup from each member to its path data (WPF) or sprite id (web)."""
    lines = [HEADER, f'namespace {namespace};', '',
             '/// <summary>The JetPack icons: Material Design Icons (Apache License 2.0), drawn on a 24×24 grid.</summary>',
             'public enum JetPackIconKind', '{', '    None,']
    lines += [f'    {name},' for name in icons]
    lines += ['}', '']
    lines += [f'internal static class {member[0]}', '{', f'    /// <summary>{member[1]}; empty for None.</summary>',
              '    public static string Get(JetPackIconKind kind) => kind switch', '    {']
    lines += [f'        JetPackIconKind.{name} => "{value}",' for name, value in icons.items()]
    lines += ['        _ => "",', '    };', '}', '']
    return '\n'.join(lines)


def sprite(data, icons):
    lines = ['<svg xmlns="http://www.w3.org/2000/svg">',
             f"<!-- Generated by tools/generate_icons.py. {data['source']}, {data['package']} {data['version']}, "
             f"{data['license']}. -->"]
    lines += [f'<symbol id="{mdi}" viewBox="0 0 24 24"><path d="{d}"/></symbol>' for mdi, d in icons.items()]
    lines.append('</svg>')
    return '\n'.join(lines) + '\n'


def outputs():
    data = manifest()
    icons = {mdi: path_data(mdi) for mdi in sorted(data['icons'])}
    return {
        OUT_WPF: enum('JetPack.Wpf.Controls', {pascal(m): d for m, d in icons.items()},
                      ('JetPackIconData', 'Path data of an icon in a 24×24 box')),
        OUT_WEB_ENUM: enum('JetPack.Web.TagHelpers', {pascal(m): m for m in icons},
                           ('JetPackIconIds', 'Id of an icon in icons.svg (its MDI name)')),
        OUT_SPRITE: sprite(data, icons),
    }


def main():
    if '--fetch' in sys.argv:
        fetch(manifest())
    files = outputs()
    if '--check' in sys.argv:
        stale = [p for p, text in files.items()
                 if not os.path.exists(p) or open(p, encoding='utf-8').read() != text]
        if stale:
            print('out of date: ' + ', '.join(os.path.relpath(p, ROOT) for p in stale) + '; run python tools/generate_icons.py')
            sys.exit(1)
        return
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', os.path.relpath(path, ROOT))


if __name__ == '__main__':
    main()
